<section aria-labelledby="v1">
	<h2 id="v1">1.0 · The new Libiamo <span class="when">(not released yet)</span></h2>
	<p>Libiamo was rebuilt around the writing you actually do.</p>
	<ul>
		<li>
			Paste what you just wrote, a post, a comment, an email, and go over it with the tutor in two passes: first what needs fixing, then how a reader
			takes it, until it says what you meant.
		</li>
		<li>
			Nothing to write? Scenarios put you in a simulated AO3, Reddit, mailbox, Discord or iMessage with people who answer, and translation scenarios
			give you a text to bring into the language you learn.
		</li>
		<li>
			Highlight phrases in anything you read to keep them; with what you learned from your own writing, they go into your notebook and come back in
			review, scheduled by FSRS.
		</li>
		<li>A week counts by its days: learn something and clear your reviews to fill a day's glass.</li>
		<li>
			Libiamo runs on your own AI key (we recommend Claude Haiku through OpenRouter), so there is no trial and no quota. Your picture is your
			Gravatar.
		</li>
	</ul>
</section>

