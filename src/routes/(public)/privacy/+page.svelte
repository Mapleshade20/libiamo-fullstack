<h1>Privacy Policy</h1>
<p class="updated">Last updated November 17, 2026</p>

<section aria-labelledby="pv-scope">
	<h2 id="pv-scope">1. Scope</h2>
	<p>
		This policy explains what the Libiamo project does with personal information when you visit the site, create an account, sign in with Google or
		GitHub, or use Libiamo to practise writing in another language.
	</p>
</section>

<section aria-labelledby="pv-what">
	<h2 id="pv-what">2. What Libiamo keeps</h2>
	<ul>
		<li>
			Your account: name, email address and whether it is confirmed, how you sign in (a password, kept only as a hash, or a linked Google or GitHub
			account), and your role.
		</li>
		<li>
			Your settings: your own language, the languages you learn, the language the tutor speaks to you, your weekly aim, your time zone, how the pages
			look, and whether you help improve Libiamo.
		</li>
		<li>Your AI provider: the provider and model you chose, and your API key, stored encrypted.</li>
		<li>
			What you write and do: your drafts and finished pieces, the steps of their revision (for a while: section 4), scenario conversations and the
			plans you type before them, translations, passages you paste to collect phrases from, your notebook, your review history and the days you
			practised.
		</li>
		<li>What you send us: scenario suggestions, and feedback with the page it was sent from and your browser's name.</li>
		<li>Records of AI requests (section 4).</li>
		<li>Security information: the IP address and browser of your signed-in sessions, and of sign-ins and account changes.</li>
	</ul>
</section>

<section aria-labelledby="pv-use">
	<h2 id="pv-use">3. How it is used</h2>
	<ul>
		<li>To run your account and keep it secure, and to send the mail it needs (confirming an address, resetting a password).</li>
		<li>To give you the features you use: the revision of what you write, scenarios, collecting phrases, the notebook, review and your week.</li>
		<li>To find and fix problems, and to improve Libiamo where you allow it (section 4).</li>
	</ul>
	<p>Libiamo shows no advertising, sells no personal information, and uses none for advertising.</p>
</section>

<section aria-labelledby="pv-ai">
	<h2 id="pv-ai">4. AI requests</h2>
	<p>
		Every AI feature runs on your own key. When you use one, Libiamo sends what the request needs (your text, what it is for, the scenario or the
		conversation) to the provider you chose, with your key. That provider's own terms, retention and training practices apply to what it receives. Do
		not put sensitive personal information in your practice that it does not need.
	</p>
	<p>
		For each request Libiamo records the model, the timing, the tokens used and the cost. If “Help improve Libiamo” is on in your settings (it is on
		for a new account), it also keeps the request and the reply, so that the project's maintainers can read sessions and fix what went wrong. These
		records are removed thirty days after the request, except those of a session a maintainer has marked as a case to fix, which are kept until the
		case is closed. The steps of a revision (what was sent and answered at each one) are kept the same way: thirty days after the piece is finished,
		or until its case is closed. A maintainer may copy a case to their own computer to reproduce it.
	</p>
	<p>
		Turning “Help improve Libiamo” off keeps only the numbers of new requests, your sessions are no longer shown to the maintainers, and the steps of
		a revision are removed once its piece is finished. Material Libiamo prepares on its own key, such as the source texts of translation scenarios,
		contains nothing of yours.
	</p>
</section>

<section aria-labelledby="pv-social">
	<h2 id="pv-social">5. Google and GitHub sign-in</h2>
	<p>
		If you sign in with Google or GitHub, the provider gives Libiamo an account identifier, your name, your email address and whether it is confirmed.
		Libiamo uses them only to sign you in, to create or link your account and to show your account. It keeps the link and the tokens the provider
		returns, and never sends them to an AI provider. Google and GitHub handle their side under their own privacy policies.
	</p>
</section>

<section aria-labelledby="pv-share">
	<h2 id="pv-share">6. Who else receives information</h2>
	<ul>
		<li>The AI provider you chose, for the requests you make (section 4).</li>
		<li>Google or GitHub, when you sign in with them.</li>
		<li>
			Gravatar: your browser asks Gravatar for the picture of a SHA-256 hash of your email address, to show it if you have one. Libiamo's server does
			not contact Gravatar.
		</li>
		<li>Cloudflare Turnstile, which checks that a person is signing up, signing in or resetting a password.</li>
		<li>The mail, hosting and database providers that run Libiamo.</li>
		<li>Authorities or others when the law requires it, or to protect people, the service or legal rights.</li>
	</ul>
	<p>Each of these may see technical details such as your IP address and browser.</p>
</section>

<section aria-labelledby="pv-keep">
	<h2 id="pv-keep">7. How long it is kept</h2>
	<p>
		Your account and what belongs to it are kept until you delete the account. Deleting it, from Settings, removes the account and everything that
		belongs to it at once: your pieces, notebook, history, key and records. Daily database backups hold a copy for up to fourteen days. Request
		records are removed sooner, as section 4 says. Providers may process information in countries other than yours.
	</p>
</section>

<section aria-labelledby="pv-cookies">
	<h2 id="pv-cookies">8. Cookies and browser storage</h2>
	<p>
		Libiamo sets a cookie that keeps you signed in, one that remembers the language you picked before signing in, and one that remembers whether the
		sidebar is folded. Your browser also keeps what you are writing and have not sent (in the home page's box, on a translation's sheet, the plan
		before a scenario, a mail in a scenario) until you send it, for thirty days at most and until you sign out, how the week's glass last moved, and,
		for the open tab, the address you typed on the sign-in pages. Cloudflare Turnstile may set its own cookies on those pages. There are no
		advertising or tracking cookies.
	</p>
</section>

<section aria-labelledby="pv-rights">
	<h2 id="pv-rights">9. Your choices and rights</h2>
	<p>
		You can change your settings, turn “Help improve Libiamo” off, change your address or password, connect or disconnect Google and GitHub, and
		delete your account, all in Settings. Depending on the law where you live, you may also ask to see, correct, export or restrict what Libiamo
		keeps, or object to how it is used: write to the address below. Libiamo may need to confirm that the account is yours first.
	</p>
</section>

<section aria-labelledby="pv-security">
	<h2 id="pv-security">10. Security</h2>
	<p>
		Passwords are kept only as hashes, your API key is encrypted, and only maintainers can read records. No online service can promise perfect
		security: keep your sign-in methods safe, and disconnect a provider or change your key if you think either was exposed.
	</p>
</section>

<section aria-labelledby="pv-children">
	<h2 id="pv-children">11. Children</h2>
	<p>
		Libiamo is not made for children. Do not create an account unless you can agree to what this policy describes yourself, or a parent or guardian
		has given any permission the law requires.
	</p>
</section>

<section aria-labelledby="pv-changes">
	<h2 id="pv-changes">12. Changes to this policy</h2>
	<p>A change shows a new date above. Where the law requires it, Libiamo will also tell you in the app or by mail before it applies.</p>
</section>

